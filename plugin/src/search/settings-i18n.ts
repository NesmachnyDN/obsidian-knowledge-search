export function translateSettings(source: string, language: string): string {
  return settingsLocale(language) === 'ru' && Object.hasOwn(russian, source) ? russian[source]! : source;
}

export function formatSettings(source: string, values: Record<string, string | number>,
  language: string): string {
  return translateSettings(source, language).replace(/\{([a-zA-Z]+)\}/g,
    (match, key: string) => Object.hasOwn(values, key) ? String(values[key]) : match);
}

export function localizeSettingsState(state: string | undefined, language: string): string {
  return translateSettings(state ?? 'none', language);
}
